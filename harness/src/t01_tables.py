def e_t04_calibration():
    """Full width, one row per model, a column group per dataset with ECE shipped, raw and
    scaled and coverage at the stated risk. Bold is the lowest ECE and the highest coverage
    of each column; a triangle marks a shipped ECE above the raw ECE, where the stored
    temperature raises the error."""
    models = DECISION_MODELS + ["comparator-open"]
    dsets = ["doneneutral", "dtwo", "dthree"]
    metrics = [("ece", "min"), ("eceraw", "min"), ("ecescaled", "min"), ("covfive", "max")]
    best = set()
    for ds in dsets:
        for met, mode in metrics:
            # the raw arm exists only where rv.raw.<model>.available says so (a09 section C)
            pool = [m for m in models if met != "eceraw" or raw_ok(m)]
            best |= best_of([f"e1.{CN.SLUG[m]}.{ds}.{met}" for m in pool], mode)

    def row(m):
        ms = CN.SLUG[m]
        cells = [mname(m)]
        for ds in dsets:
            p = f"e1.{ms}.{ds}"
            # the marker compares unrounded values, so a rise hidden by rounding still shows
            ship = NUM[f"{p}.ece"]["value"] if printed(f"{p}.ece") is not None else None
            raw = (NUM[f"{p}.eceraw"]["value"]
                   if raw_ok(m) and printed(f"{p}.eceraw") is not None else None)
            up = ship is not None and raw is not None and ship > raw
            cells.append(ecell(f"{p}.ece", best, "\\mkup" if up else None, slot=True))
            cells += [ecell(f"{p}.eceraw", best) if raw_ok(m) else "--",
                      ecell(f"{p}.ecescaled", best), ecell(f"{p}.covfive", best)]
        return [" & ".join(cells) + " \\\\"]

    rest = (1.0 - 0.196 - 3 * 0.072) / 9
    spec = colspec([("P", 0.196)] + ([("N", 0.072)] + [("N", rest)] * 3) * 3)
    lines = EAAI_HEADER + [
        "\\tablestylewide",
        "\\begin{tabular}{%s}" % spec,
        "\\toprule",
        "\\headrow \\hdtop{} & \\hdgroup{four}{D1 typed-decisions} & \\hdgroup{four}{D2 CLINC-150}"
        " & \\hdgroup{four}{D3 pooled} \\\\",
        "\\bandrules{2-5,6-9,10-13}",
        "\\headrow \\hdsub{Model}" + (" & \\hdsub{Ship.\\mk{}} & \\hdsub{Raw} & \\hdsub{Scal.}"
                                     " & \\hdsub{Cov.}") * 3 + " \\\\",
        "\\midrule"]
    lines += family_rows(models, 13, row)
    lines += ["\\bottomrule", "\\end{tabular}",
              "\\tablenote{Ship., Raw and Scal.\\ are the expected calibration error as shipped,"
              " at a temperature of one and after scaling, and Cov.\\ is the coverage at"
              " \\num{p.riskfive} percent risk as shipped. The raw arm exists only where the"
              " served temperature is known and the temperature-one distribution is stored,"
              " so Jev 1.13.0 and the generative comparator have none. Bold marks the lowest"
              " error and the highest coverage in each column, with ties bolded, and \\mkup\\"
              " marks a shipped error above the raw error before rounding, where the stored"
              " temperature raises the error.}"]
    return ewrite("t04_calibration.tex", lines)


def raw_ok(m):
    """True when the model has a raw (temperature-one) arm, per rv.raw.<model>.available."""
    lab = f"rv.raw.{CN.SLUG[m]}.available"
    return has(lab) and NUM[lab]["value"] == "yes"


