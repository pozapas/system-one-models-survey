def flip_glyph(flips, floor):
    """Three-level scale of flips in excess of the test-retest floor, per hundred decisions:
    below one (the order of the hosted model's own floor), one to ten, ten or more."""
    if flips is None:
        return ""
    excess = round(flips - (floor or 0.0), 1)    # flips and floors print to one decimal
    if excess < 1.0:
        return "\\symnone"
    if excess < 10.0:
        return "\\symhalf"
    return "\\symfull"


