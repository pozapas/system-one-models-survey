"""Write the LaTeX tabular bodies for Paper 4A from results/numbers.json.

Every number in these tables is a \\num{label} macro defined by collect_numbers.py,
never a literal, so run that script first (and after any label change). A model
row with no data for a given cell prints an en dash, and every table lists every
model in style.MODEL_COLORS order, so the tables do not change shape as open-model
results land; only their dashes fill in.

Output: ./tables/ (set TABLES_DIR to change)
"""
