# EAAI mode (python t01_tables.py --eaai). Writes the redesigned tables of the journal
# version to EAAI_TABLES_DIR in the visual system of paper4a_tables.sty: a green header
# band, family group rows, model swatches in the figure palette, bold best values and
# symbol markers computed here from numbers.json at printed precision. Every numeric
# cell shows the same \num label as the ACL table of the same name; eaai_main() checks
# that against the ACL files before it returns. The default mode above is unchanged.

EAAI_TABLES_DIR = os.environ.get("EAAI_TABLES_DIR", os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tables_eaai"))

FAMILIES = [("Hosted", ["jev-1.13.0"]),
            ("Open, encoder head", ["laya-en", "laya-ml"]),
            ("Open, decoder head", ["kev-0.8b", "kev-9b", "decider-2b", "this-that-1.0",
                                    "nimble-9b"]),
            ("Generative comparator", ["comparator-open"])]
WORDS = {2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight",
         9: "nine", 10: "ten", 11: "eleven", 12: "twelve", 13: "thirteen"}

EAAI_HEADER = ["% Generated by shared/src/t01_tables.py --eaai. Do not edit by hand.",
               "% Every numeric cell is a num-macro from numbers.tex; -- means that",
               "% model has no result for this cell yet. Needs paper4a_tables.sty."]


def printed(label):
    """The value of a label as the manuscript prints it, as a float, or None."""
    if not has(label):
        return None
    rec = NUM[label]
    v = rec["value"]
    if isinstance(v, str):
        return None
    fmt = rec.get("fmt")
    return float(format(v, fmt)) if fmt else float(v)


def best_of(labels, mode):
    """Labels holding the best printed value (max or min); ties are all returned."""
    vals = {l: printed(l) for l in labels}
    vals = {l: v for l, v in vals.items() if v is not None}
    if not vals:
        return set()
    b = max(vals.values()) if mode == "max" else min(vals.values())
    return {l for l, v in vals.items() if v == b}


def ecell(label, best=(), mark=None, slot=False):
    """A numeric cell: \\num{label}, bold when best, with an optional marker slot."""
    if not has(label):
        s = "--"
    else:
        s = "\\num{%s}" % label
        if label in best:
            s = "\\best{%s}" % s
    if slot:
        s += "\\mk{%s}" % (mark or "")
    return s


def mname(m):
    return "\\msw{%s}%s" % (CN.SLUG[m], style.MODEL_LABELS[m])


def groupspan(ncols, label):
    return "\\groupspan{%s}{%s}" % (WORDS[ncols], label)


def colspec(parts):
    """parts: list of (type, fraction). The fractions must sum to one, so the band and
    the rules span \\linewidth exactly."""
    total = sum(f for _t, f in parts)
    assert abs(total - 1.0) < 1e-9, total
    return "".join("%s{%.4f}" % (t, f) for t, f in parts)


def ewrite(name, lines):
    os.makedirs(EAAI_TABLES_DIR, exist_ok=True)
    path = os.path.join(EAAI_TABLES_DIR, name)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"  wrote {path}")
    return path


def family_rows(models, ncols, row_fn, between=None):
    """Group rows by model family, skipping families with no model in `models`;
    `between` is a line put between two models of the same family."""
    out = []
    for fam, members in FAMILIES:
        ms = [m for m in members if m in models]
        if not ms:
            continue
        out.append(groupspan(ncols, fam))
        for i, m in enumerate(ms):
            if between and i:
                out.append(between)
            out += row_fn(m)
    return out


