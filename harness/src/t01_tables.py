def ivcell(prefix, lo="lo", hi="hi"):
    """A muted interval [lo, hi] for a separate left-aligned column; empty when missing."""
    a, b = f"{prefix}{lo}", f"{prefix}{hi}"
    if not (has(a) and has(b)):
        return ""
    return "{\\scriptsize\\cellnote{[\\num{%s}, \\num{%s}]}}" % (a, b)


def stack(value_cell, prefix, lo="lo", hi="hi"):
    """A value with its muted interval on a second line of the same cell. The break is a new
    paragraph, so both lines keep the column's alignment (\\newline would add \\hfil and push
    the value to the left)."""
    iv = ivcell(prefix, lo, hi)
    return value_cell + ("\\par" + iv if iv and value_cell != "--" else "")


