def printed(label):
    """The value of a label as the manuscript prints it, as a float, or None."""
    if not has(label):
        return None
    rec = NUM[label]
    v = rec["value"]
    if isinstance(v, str):
        return None
    fmt = rec.get("fmt")
    return float(format(v, fmt)) if fmt else float(v)


def best_of(labels, mode):
    """Labels holding the best printed value (max or min); ties are all returned."""
    # Laya (multilingual) on the full intent list works on truncated option keys (its
    # option text exceeds the input budget), so its cells there are shown but not ranked
    vals = {l: printed(l) for l in labels
            if not ("layaml" in l and ("dtwo" in l or "d2k150" in l or l.startswith("e3.")))}
    vals = {l: v for l, v in vals.items() if v is not None}
    if not vals:
        return set()
    b = max(vals.values()) if mode == "max" else min(vals.values())
    return {l for l, v in vals.items() if v == b}


def ecell(label, best=(), mark=None, slot=False):
    """A numeric cell: \\num{label}, bold when best, with an optional marker slot."""
    if not has(label):
        s = "--"
    else:
        s = "\\num{%s}" % label
        if label in best:
            s = "\\best{%s}" % s
    if slot:
        s += "\\mk{%s}" % (mark or "")
    return s


def mname(m):
    return "\\msw{%s}%s" % (CN.SLUG[m], style.MODEL_LABELS[m])


def groupspan(ncols, label):
    return "\\groupspan{%s}{%s}" % (WORDS[ncols], label)


def colspec(parts):
    """parts: list of (type, fraction). The fractions must sum to one, so the band and
    the rules span \\linewidth exactly."""
    total = sum(f for _t, f in parts)
    assert abs(total - 1.0) < 1e-9, total
    return "".join("%s{%.4f}" % (t, f) for t, f in parts)


def with_tabhead(lines):
    """Insert \\tabhead after the \\midrule that closes each header block (a \\midrule that
    directly follows a \\headrow line). It expands to nothing in a tabular and to \\endhead
    in an appendix longtable (\\longtab in paper4a_tables.sty)."""
    out = []
    for i, l in enumerate(lines):
        out.append(l)
        if l.strip() == "\\midrule" and i and lines[i - 1].lstrip().startswith("\\headrow"):
            out.append("\\tabhead")
    return out


def keep_last_rows(lines, n=3):
    """End the last n body rows before each \\bottomrule with \\\\* instead of \\\\, so a
    longtable never leaves one or two rows alone on a new page (in a tabular \\\\* is the same
    as \\\\)."""
    out = list(lines)
    for i, l in enumerate(out):
        if l.strip() != "\\bottomrule":
            continue
        k, j = 0, i - 1
        while j >= 0 and k < n and not out[j].lstrip().startswith(("\\midrule", "\\tabhead")):
            if out[j].rstrip().endswith(" \\\\"):
                out[j] = out[j].rstrip() + "*"
                k += 1
            j -= 1
    return out


def ewrite(name, lines):
    lines = keep_last_rows(with_tabhead(lines))
    os.makedirs(EAAI_TABLES_DIR, exist_ok=True)
    path = os.path.join(EAAI_TABLES_DIR, name)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"  wrote {path}")
    return path


def family_rows(models, ncols, row_fn, between=None):
    """Group rows by model family, skipping families with no model in `models`;
    `between` is a line put between two models of the same family."""
    out = []
    for fam, members in FAMILIES:
        ms = [m for m in members if m in models]
        if not ms:
            continue
        if len(ms) > 1 and fam.endswith("comparator"):
            fam += "s"
        out.append(groupspan(ncols, fam))
        for i, m in enumerate(ms):
            if between and i:
                out.append(between)
            elif i and m in COMP_BASE and COMP_BASE[m] != COMP_BASE.get(ms[i - 1]):
                out.append("\\addlinespace[2.5pt]")
            out += row_fn(m)
    return out



