def eaai_main():
    load_numbers()
    paths = [e_t03_headline(), e_t04_calibration(), e_t05_cardinality(), e_t06_names(),
             e_t07_cost(), e_t08_cascade(), e_t09_calib_tasks(), e_t10_selective(),
             e_t11_paired(), e_t12_manifest(), e_t13_gate(), e_t16_scores(),
             e_t17_backbones(), e_t18_oos_option(), e_t19_new_tasks(),
             e_t20_readouts(), e_t21_risk_control(), e_t22_cascade_qwen()]
    import re
    used = set()
    for p in paths:
        text = open(p, encoding="utf-8").read()
        used |= set(re.findall(r"\\num\{([^}]+)\}", text))
        used |= set(x for grp in re.findall(r"\\valbar\{([^}]+)\}\{([^}]+)\}\{([^}]*)\}", text)
                    for x in grp if x)
        # Every other EAAI table shows exactly the numeric labels and dashes of the ACL table.
        acl = os.path.join(TABLES_DIR, os.path.basename(p))
        if os.path.exists(acl) and os.path.basename(p) not in EAAI_DIVERGES:
            new, old = _body_labels(text), _body_labels(open(acl, encoding="utf-8").read())
            if new != old:
                raise SystemExit(f"{os.path.basename(p)}: numeric cells differ from the ACL"
                                 f" table ({len(new[0])} vs {len(old[0])} labels,"
                                 f" {new[1]} vs {old[1]} dashes)")
    missing = sorted(l for l in used if l not in NUM)
    if missing:
        raise SystemExit(f"{len(missing)} labels used in tables are not in numbers.json: "
                          f"{missing[:10]}")
    print(f"all {len(used)} distinct labels used in the EAAI tables exist in numbers.json,"
          " and every table with an ACL counterpart outside EAAI_DIVERGES shows its numeric"
          " cells")
    for name, labs in E_MARKS.items():
        print(f"  {name}: {len(labs)} bold or marked cells: {', '.join(labs)}")


